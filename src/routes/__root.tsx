import { AuthProvider, useAuth } from "@/lib/auth-context";
import { useRouterState, useNavigate } from "@tanstack/react-router";

const PUBLIC_AUTH_PATHS = [
  "/login",
  "/register",
  "/forgot-password",
  "/reset-password",
  "/verify-email",
  "/auth/google/callback",
];

function ProtectedAppLayout() {
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const navigate = useNavigate();
  const { isAuthenticated, isLoading } = useAuth();

  const isPublicAuthRoute = PUBLIC_AUTH_PATHS.some(
    (p) => pathname === p || pathname.startsWith(p)
  );

  useEffect(() => {
    if (!isLoading && !isAuthenticated && !isPublicAuthRoute) {
      navigate({
        to: "/login",
        search: { redirect: pathname !== "/login" ? pathname : "/" },
      });
    }
  }, [isLoading, isAuthenticated, isPublicAuthRoute, pathname, navigate]);

  if (isPublicAuthRoute) {
    return <Outlet />;
  }

  if (isLoading) {
    return (
      <div className="flex min-h-screen w-full flex-col items-center justify-center bg-background text-foreground">
        <div className="flex flex-col items-center gap-3">
          <div className="size-8 animate-spin rounded-full border-2 border-primary border-t-transparent" />
          <div className="font-mono text-xs tracking-widest text-muted-foreground uppercase">
            Restoring SentinelAI Session...
          </div>
        </div>
      </div>
    );
  }

  if (!isAuthenticated) {
    return null;
  }

  return (
    <SidebarProvider>
      <div className="flex min-h-screen w-full">
        <AppSidebar />
        <div className="flex min-w-0 flex-1 flex-col">
          <AppHeader />
          <main className="flex-1 p-4 md:p-6">
            <Outlet />
          </main>
        </div>
      </div>
    </SidebarProvider>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <ThemeProvider>
        <TooltipProvider>
          <AuthProvider>
            <ProtectedAppLayout />
            <Toaster richColors position="bottom-right" />
          </AuthProvider>
        </TooltipProvider>
      </ThemeProvider>
    </QueryClientProvider>
  );
}

